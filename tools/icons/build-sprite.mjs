// Build webapp/icons.fluent.svg from Fluent UI System Icons (MIT) — UX-SHELL-16.
//
//   cd tools/icons && npm ci && npm run build
//
// The sprite is generated, never hand-edited: every symbol traces to a file in
// a pinned package, which is the provenance the old 628-symbol sprite lacked.
// Icons with no Fluent equivalent are drawn in-house below, to the same 20px
// grid, and listed here so their origin is recorded too.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "node_modules/@fluentui/svg-icons/icons");
const out = path.join(here, "../../webapp/icons.fluent.svg");

const IN_HOUSE = {
  // A six-point asterisk for the find bar's wildcard option; Fluent has none.
  asterisk: "M10 3.5a.5.5 0 0 1 .5.5v5.13l4.44-2.57a.5.5 0 1 1 .5.87L11 10l4.44 2.57a.5.5 0 1 1-.5.87L10.5 10.87V16a.5.5 0 0 1-1 0v-5.13l-4.44 2.57a.5.5 0 1 1-.5-.87L9 10 4.56 7.43a.5.5 0 1 1 .5-.87L9.5 9.13V4a.5.5 0 0 1 .5-.5Z",
  // A general percent sign; Fluent has none outside composite glyphs.
  percent: "M6 3.5a2.5 2.5 0 1 1 0 5a2.5 2.5 0 0 1 0-5Zm0 1a1.5 1.5 0 1 0 0 3a1.5 1.5 0 0 0 0-3Zm8 7a2.5 2.5 0 1 1 0 5a2.5 2.5 0 0 1 0-5Zm0 1a1.5 1.5 0 1 0 0 3a1.5 1.5 0 0 0 0-3ZM15.35 4.65a.5.5 0 0 1 0 .7l-10 10a.5.5 0 0 1-.7-.7l10-10a.5.5 0 0 1 .7 0Z",
};

const names = fs.readFileSync(path.join(here, "icons.txt"), "utf8")
  .split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));

const symbols = [];
const missing = [];
for (const name of names) {
  const file = path.join(src, `${name}_20_regular.svg`);
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const svg = fs.readFileSync(file, "utf8");
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => `<path d="${m[1]}"/>`);
  symbols.push(`<symbol id="fi-${name}" viewBox="0 0 20 20">${paths.join("")}</symbol>`);
}
for (const [name, d] of Object.entries(IN_HOUSE)) {
  symbols.push(`<symbol id="fi-${name}" viewBox="0 0 20 20"><path d="${d}"/></symbol>`);
}
if (missing.length) {
  console.error(`missing from @fluentui/svg-icons: ${missing.join(", ")}`);
  process.exit(1);
}
const pkg = JSON.parse(fs.readFileSync(path.join(here, "node_modules/@fluentui/svg-icons/package.json"), "utf8"));
fs.writeFileSync(out,
  `<!-- Generated by tools/icons/build-sprite.mjs from @fluentui/svg-icons ${pkg.version} (MIT, Copyright Microsoft Corporation). Do not edit. -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true" id="oc-fluent-icons" fill="currentColor">\n${symbols.join("\n")}\n</svg>\n`);
console.log(`wrote ${symbols.length} symbols to ${path.relative(process.cwd(), out)}`);
