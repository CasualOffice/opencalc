#!/usr/bin/env python3
"""`docs/96` shows each Excel-parity row's status as `docs/14` records it.

`docs/96` is the Excel fit-gap analysis: every `XL-FEAT-*` and `XL-UX-*` row
with its evidence, written once on 2026-10-14. The tracker moved on and the
analysis did not. Three weeks later 72 of its rows were `Done` and it still
presented `XL-FEAT-001..010` as the live P0s, its priority table still counted
the original 253, and 88 rows filed since were in the tracker and nowhere in
the document people were reading for "how close are we to Excel?" (`DOC-054`).

That is the same failure as `docs/46` and `docs/48`: a second list that nobody
re-derives. Nobody had to be careless for it to happen. A row is closed by the
work that closes it, in `docs/14`, and nothing anywhere asked about `docs/96`.

So the status is not maintained by hand here. This gate owns three things in
`docs/96`, all derived from the trackers:

- an `St` column, second in every table whose rows are `XL-*` ids;
- the block between the `fit-gap-status` markers: counts by status and
  severity, and every tracker row the tables do not list yet;
- the refusal of an `XL-*` id in `docs/96` that no tracker defines.

Run with `--write` to regenerate; without it, it fails if regenerating would
change anything. The prose — the parity-by-area table, the evidence columns —
is still written by people, and this gate cannot tell when *that* is stale.
What it does is make a stale status impossible, so a reader never has to.
"""

import collections
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from tracker_rows import cells, rows  # noqa: E402

FIT_GAP = pathlib.Path("docs/96-EXCEL-FIT-GAP.md")
TRACKERS = [
    pathlib.Path("docs/14-EXECUTION-TRACKER.md"),
    pathlib.Path("docs/14a-ARCHIVE-CLOSED-WORK.md"),
]
BEGIN = "<!-- fit-gap-status:begin (generated by tools/check-fit-gap-status.py --write; do not edit) -->"
END = "<!-- fit-gap-status:end -->"
CLOSED = ("Done", "Dropped")
ORDER = ["Open", "WIP", "Partial", "Designed", "Blocked", "Done", "Dropped"]
SEVS = ["P0", "P1", "P2", "P3"]
# An unescaped `|` — the same rule `tracker_rows.cells` reads by.
PIPE = re.compile(r"(?<!\\)\|")


def is_parity(rid: str) -> bool:
    return rid.startswith("XL-FEAT-") or rid.startswith("XL-UX-")


def tracker_rows():
    found = {}
    for path in TRACKERS:
        for _, rid, line in rows(path.read_text(encoding="utf-8")):
            if is_parity(rid):
                c = cells(line)
                found[rid] = {"title": c[1], "st": c[2], "sev": c[3]}
    return found


def raw_cells(line: str) -> list[str]:
    """Cells with their own spacing kept, so a rewrite touches one cell only."""
    return PIPE.split(line.strip())[1:-1]


def join(parts: list[str]) -> str:
    return "|" + "|".join(parts) + "|"


def with_status(lines: list[str], tracker: dict, listed: set, unknown: list):
    """Put `St` second in every `XL-*` table, valued from the tracker."""
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        header = raw_cells(line) if line.startswith("|") else []
        if (
            header
            and header[0].strip() == "ID"
            and i + 2 < len(lines)
            and is_parity(cells(lines[i + 2])[0] if lines[i + 2].startswith("|") else "")
        ):
            has_st = len(header) > 1 and header[1].strip() == "St"
            if not has_st:
                header.insert(1, " St ")
            out.append(join(header))
            sep = raw_cells(lines[i + 1])
            if not has_st:
                sep.insert(1, "---")
            out.append(join(sep))
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                parts = raw_cells(lines[i])
                rid = parts[0].strip()
                if is_parity(rid):
                    listed.add(rid)
                    st = tracker.get(rid, {}).get("st")
                    if st is None:
                        unknown.append(rid)
                        st = "?"
                    cell = f" {st} "
                    if has_st:
                        parts[1] = cell
                    else:
                        parts.insert(1, cell)
                out.append(join(parts))
                i += 1
            continue
        out.append(line)
        i += 1
    return out


def summary(tracker: dict, listed: set) -> list[str]:
    by = collections.Counter((r["st"], r["sev"]) for r in tracker.values())
    sts = [s for s in ORDER if any(by[(s, v)] for v in SEVS)]
    sts += sorted({s for s, _ in by} - set(sts))
    out = [
        BEGIN,
        "",
        f"**Status, from the tracker.** {len(tracker)} parity rows; "
        f"{sum(1 for r in tracker.values() if r['st'] in CLOSED)} closed, "
        f"{sum(1 for r in tracker.values() if r['st'] not in CLOSED)} still open. "
        "Severity is the tracker's, which may since differ from the `Pri` the "
        "audit gave a row below.",
        "",
        "| St | " + " | ".join(SEVS) + " | Total |",
        "| --- | " + " | ".join("---" for _ in SEVS) + " | --- |",
    ]
    for s in sts:
        n = [by[(s, v)] for v in SEVS]
        out.append(f"| {s} | " + " | ".join(str(x) for x in n) + f" | {sum(n)} |")
    late = sorted(
        (rid for rid in tracker if rid not in listed),
        key=lambda r: (r.split("-")[1], int(r.rsplit("-", 1)[1])),
    )
    if late:
        out += [
            "",
            f"**Filed since the audit — {len(late)} rows** the tables below do not "
            "list. Their evidence is in the tracker row.",
            "",
            "| ID | St | Sev | Title |",
            "| --- | --- | --- | --- |",
        ]
        out += [
            f"| {rid} | {tracker[rid]['st']} | {tracker[rid]['sev']} | {tracker[rid]['title']} |"
            for rid in late
        ]
    out += ["", END]
    return out


def render(text: str, tracker: dict):
    lines = text.splitlines()
    if BEGIN not in lines or END not in lines:
        raise SystemExit(
            f"{FIT_GAP}: the `fit-gap-status` markers are missing — put them "
            "where the generated status block belongs"
        )
    a, b = lines.index(BEGIN), lines.index(END)
    # The generated block is itself a table of `XL-*` rows. Read as one of the
    # audit's tables, its rows count as "listed" and the next run drops them —
    # so the gate failed on its own output. It is cut out before the pass.
    before, after = lines[:a], lines[b + 1 :]
    listed, unknown = set(), []
    before = with_status(before, tracker, listed, unknown)
    after = with_status(after, tracker, listed, unknown)
    lines = before + summary(tracker, listed) + after
    return "\n".join(lines) + "\n", unknown


def main() -> int:
    write = "--write" in sys.argv[1:]
    text = FIT_GAP.read_text(encoding="utf-8")
    new, unknown = render(text, tracker_rows())
    problems = [
        f"{FIT_GAP} lists `{rid}`, which no tracker defines" for rid in unknown
    ]
    if new != text:
        if write:
            FIT_GAP.write_text(new, encoding="utf-8")
            print(f"fit-gap status: rewrote {FIT_GAP}")
        else:
            problems.append(
                f"{FIT_GAP} does not show the tracker's status — run "
                "`python3 tools/check-fit-gap-status.py --write` and commit it"
            )
    for p in problems:
        print(f"::error::{p}")
    if not problems:
        print(f"fit-gap status: {FIT_GAP} agrees with the tracker")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
